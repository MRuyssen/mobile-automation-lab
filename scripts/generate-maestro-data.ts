import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { StaticProvider } from "@mal/test-data";

const OUT_DIR = path.resolve(import.meta.dirname, "..", "maestro", ".generated");
const OUT_FILE = path.join(OUT_DIR, "data.js");

async function main(): Promise<void> {
  const users = {
    valid: await StaticProvider.users.valid(),
    invalidEmail: await StaticProvider.users.invalidEmail(),
    shortPassword: await StaticProvider.users.shortPassword(),
  };
  const texts = await StaticProvider.texts();
  const forms = await StaticProvider.forms();
  const swipe = await StaticProvider.swipe();
  const persistence = await StaticProvider.persistence();

  const data = { users, texts, forms, swipe, persistence };

  mkdirSync(OUT_DIR, { recursive: true });

  // Maestro's runScript gives the flow access to `output` object.
  // We assign all data properties directly onto output so flows can
  // reference them as ${output.users.valid.email} etc.
  const js = [
    "// Auto-generated by npm run data:maestro — do not edit",
    `var data = ${JSON.stringify(data, null, 2)};`,
    "",
    "// Flatten into output for Maestro flow access",
    "Object.assign(output, data);",
    "",
  ].join("\n");

  writeFileSync(OUT_FILE, js);
  console.log(`Generated ${OUT_FILE}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
